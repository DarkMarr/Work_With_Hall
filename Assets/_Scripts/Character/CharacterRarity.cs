namespace QuizGame.Character
{
    /// <summary>
    /// Avatar rarity from the avatar design sheet. None = base/species character (not an avatar).
    /// </summary>
    public enum CharacterRarity
    {
        None = 0,
        Uncommon = 1,
        Rare = 2,
        UltraRare = 3,
    }

    public enum CharacterSpecies
    {
        None = 0,
        Cat = 1,
        Dog = 2,
        Rabbit = 3,
    }
}
